"""Storage interface used by services.

Two implementations:
* ``app.storage.memory.MemoryRepository`` — in-process, used by the unit test-suite and
  emulating the database constraints (unique keys, one active subscription, ...);
* ``app.storage.sql.SqlRepository`` — PostgreSQL via SQLAlchemy 2 (async).
"""

from __future__ import annotations

from contextlib import AbstractAsyncContextManager
from datetime import datetime
from decimal import Decimal
from typing import Any, Protocol

from app.domain.models import (
    Listing,
    Notification,
    Payment,
    Plan,
    Search,
    SourceState,
    StoredListing,
    Subscription,
    User,
)


class UpsertResult:
    __slots__ = ("listing", "is_new", "old_price")

    def __init__(self, listing: StoredListing, is_new: bool, old_price: Decimal | None) -> None:
        self.listing = listing
        self.is_new = is_new
        self.old_price = old_price


class Repository(Protocol):
    def transaction(self) -> AbstractAsyncContextManager[None]: ...

    # users
    async def get_user(self, user_id: int) -> User | None: ...
    async def get_user_by_telegram_id(self, telegram_id: int) -> User | None: ...
    async def create_user(self, telegram_id: int, username: str | None, first_name: str | None,
                          language: str, timezone: str, now: datetime) -> User: ...
    async def update_user(self, user_id: int, **fields: Any) -> None: ...
    async def delete_user_data(self, user_id: int, now: datetime) -> None: ...

    # plans
    async def list_plans(self, active_only: bool = True) -> list[Plan]: ...
    async def get_plan(self, plan_id: int) -> Plan | None: ...
    async def get_plan_by_code(self, code: str) -> Plan | None: ...
    async def upsert_plan(self, plan: Plan) -> Plan: ...
    async def update_plan(self, code: str, **fields: Any) -> None: ...

    # subscriptions
    async def get_active_subscription(self, user_id: int) -> Subscription | None: ...
    async def create_subscription(self, user_id: int, plan_id: int, origin: str, starts_at: datetime,
                                  expires_at: datetime, payment_id: int | None) -> Subscription: ...
    async def set_subscription_status(self, subscription_id: int, status: str,
                                      expires_at: datetime | None = None) -> None: ...
    async def list_expired_active_subscriptions(self, now: datetime, limit: int) -> list[Subscription]: ...
    async def mark_expiry_notified(self, subscription_id: int, now: datetime) -> None: ...
    async def list_unnotified_expired(self, limit: int) -> list[Subscription]: ...

    # searches
    async def create_search(self, search: Search) -> Search: ...
    async def get_search(self, search_id: int) -> Search | None: ...
    async def list_user_searches(self, user_id: int) -> list[Search]: ...
    async def update_search(self, search_id: int, **fields: Any) -> None: ...
    async def delete_search(self, search_id: int) -> None: ...
    async def list_due_searches(self, now: datetime, limit: int) -> list[Search]: ...

    # listings, matches, runs
    async def upsert_listing(self, listing: Listing, now: datetime) -> UpsertResult: ...
    async def get_listing(self, listing_id: int) -> StoredListing | None: ...
    async def add_match(self, search_id: int, listing_id: int, user_id: int, reasons: list) -> bool: ...
    async def add_run(self, search_id: int, source: str, started_at: datetime, finished_at: datetime,
                      status: str, fetched: int, new_listings: int, matched: int, error: str | None) -> None: ...

    # notifications
    async def enqueue_notification(self, user_id: int, listing_id: int, search_id: int | None, kind: str,
                                   dedup_key: str, price: Decimal | None, next_attempt_at: datetime) -> bool: ...
    async def claim_notifications(self, now: datetime, limit: int, stale_after_seconds: int = 300) -> list[Notification]: ...
    async def finish_notification(self, notification_id: int, status: str, now: datetime,
                                  error: str | None = None, message_id: int | None = None,
                                  next_attempt_at: datetime | None = None, count_attempt: bool = True) -> None: ...
    async def count_sent_since(self, user_id: int, since: datetime) -> int: ...
    async def find_user_listing_match(self, user_id: int, listing_id: int) -> tuple[int, StoredListing] | None: ...
    async def list_recent_matches(self, search_id: int, since: datetime, limit: int) -> list[StoredListing]: ...
    async def find_listing_by_message(self, user_id: int, telegram_message_id: int) -> int | None: ...
    async def list_comparable_prices(self, search_id: int, exclude_listing_id: int, since: datetime,
                                     currency: str | None, condition: str | None, limit: int = 500) -> list[Decimal]: ...

    # sources
    async def get_source_state(self, source: str) -> SourceState | None: ...
    async def save_source_state(self, state: SourceState, now: datetime) -> None: ...
    async def list_source_states(self) -> list[SourceState]: ...

    # payments
    async def record_payment_event(self, provider: str, event_type: str, external_event_id: str,
                                   payload: dict, now: datetime) -> tuple[int, bool]: ...
    async def finish_payment_event(self, event_id: int, now: datetime, payment_id: int | None,
                                   error: str | None) -> None: ...
    async def get_payment_by_charge_id(self, charge_id: str) -> Payment | None: ...
    async def create_payment(self, payment: Payment) -> Payment: ...
    async def update_payment(self, payment_id: int, **fields: Any) -> None: ...
    async def list_user_payments(self, user_id: int, limit: int = 20) -> list[Payment]: ...
    async def list_payment_errors(self, limit: int = 20) -> list[dict]: ...
    async def create_refund(self, payment_id: int, amount: Decimal, reason: str | None, status: str,
                            admin_telegram_id: int | None, error: str | None, now: datetime) -> int: ...

    # admin / ops
    async def add_audit(self, admin_telegram_id: int, action: str, target: str | None, details: dict,
                        now: datetime) -> None: ...
    async def list_audit(self, limit: int = 20) -> list[dict]: ...
    async def stats(self, now: datetime) -> dict[str, int]: ...
    async def purge_old_data(self, listings_before: datetime, runs_before: datetime,
                             notifications_before: datetime) -> dict[str, int]: ...
